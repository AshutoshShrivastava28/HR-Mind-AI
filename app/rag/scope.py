_HR_SCOPE_PATTERN = re.compile(
    r"\b(?:" + "|".join(re.escape(term) for term in _HR_SCOPE_TERMS) + r")\b",
    re.IGNORECASE,
)

OUT_OF_SCOPE_REPLY = (
    "I'm HR Mind AI, an HR and employee-support copilot. I can help with "
    "workplace policies, leave, benefits, payroll, hiring, onboarding, "
    "remote work, employee relations, and other HR topics. I can't answer "
    "general questions such as the weather. Please rephrase your question "
    "around an HR or workplace need."
)


def is_hr_related_question(question: str) -> bool:
    """Allow HR/workplace requests to reach retrieval and block other topics."""
    normalized = unicodedata.normalize("NFKC", str(question or "")).casefold()
    normalized = re.sub(r"[-_/]+", " ", normalized)
    normalized = " ".join(normalized.split())
    return bool(_HR_SCOPE_PATTERN.search(normalized))
